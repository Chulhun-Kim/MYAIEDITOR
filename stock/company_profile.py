def get_company_profile(name: str = "", ticker: str = "") -> Dict[str, Any]:
    """
    종목명 기준으로 기업 프로파일을 반환한다.
    ticker는 향후 확장용으로 받는다.
    """
    name = str(name or "").strip()

    if not name:
        return {}

    if name in COMPANY_PROFILES:
        return COMPANY_PROFILES[name]

    # 일부 표기 차이 보정
    aliases = {
        "JYP": "JYP Ent.",
        "JYP엔터": "JYP Ent.",
        "HD현대미포": "HD현대중공업",
    }

    canonical = aliases.get(name)
    if canonical and canonical in COMPANY_PROFILES:
        return COMPANY_PROFILES[canonical]

    return {}


def get_company_reason(name: str = "", ticker: str = "") -> str:
    profile = get_company_profile(name=name, ticker=ticker)
    return str(profile.get("reason", "") or "").strip()


def get_company_watch(name: str = "", ticker: str = "") -> str:
    profile = get_company_profile(name=name, ticker=ticker)
    return str(profile.get("watch", "") or "").strip()


def get_company_sector(name: str = "", ticker: str = "") -> str:
    profile = get_company_profile(name=name, ticker=ticker)
    return str(profile.get("sector", "") or "").strip()


def get_company_keywords(name: str = "", ticker: str = "") -> List[str]:
    profile = get_company_profile(name=name, ticker=ticker)
    keywords = profile.get("keywords", []) or []
    return [str(k).strip() for k in keywords if str(k).strip()]
